import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Annotated, Literal

from pydantic import AfterValidator, BaseModel, ConfigDict, Field, StringConstraints

from app.models.catalog import BaseUnit, Unit
from app.models.stock import DocStatus, DocType, WriteOffReason


def _aware(v: datetime) -> datetime:
    if v.tzinfo is None:
        raise ValueError("doc_date must include a time zone offset")
    return v


AwareDatetime = Annotated[datetime, AfterValidator(_aware)]
PositiveQty = Annotated[Decimal, Field(gt=0, max_digits=14, decimal_places=3)]
Money = Annotated[Decimal, Field(ge=0, max_digits=14, decimal_places=2)]
Comment = Annotated[str, StringConstraints(strip_whitespace=True, max_length=1000)]


class QtyIn(BaseModel):
    product_id: int
    qty: PositiveQty
    # Unit the quantity is expressed in; defaults to the product's own unit (architecture section 2).
    qty_unit: Unit | None = None


class ReceiptLineIn(QtyIn):
    location_id: int
    # Per product unit, as on the invoice. Optional (owner, reply 59: no money in receipts): without it the cost is
    # the product's current price and the price is left unchanged.
    unit_price: Money | None = None


class WriteOffLineIn(QtyIn):
    location_id: int


class DocCommon(BaseModel):
    id: uuid.UUID  # generated by the client; retries with the same id are idempotent
    doc_date: AwareDatetime | None = None  # defaults to now
    comment: Comment = ""
    confirm_backdate: bool = False


class ReceiptIn(DocCommon):
    # Currency of unit_price: USD is converted to won at settings.usd_krw_rate and rounded to whole won (reply 34).
    price_currency: Literal["KRW", "USD"] = "KRW"
    supplier: Annotated[str, StringConstraints(strip_whitespace=True, max_length=128)] | None = None
    invoice_no: Annotated[str, StringConstraints(strip_whitespace=True, max_length=64)] | None = None
    lines: list[ReceiptLineIn] = Field(min_length=1, max_length=500)


class WriteOffIn(DocCommon):
    reason: WriteOffReason
    allow_negative: bool = False
    lines: list[WriteOffLineIn] = Field(min_length=1, max_length=500)


class TransferIn(DocCommon):
    from_location_id: int
    to_location_id: int
    allow_negative: bool = False
    lines: list[QtyIn] = Field(min_length=1, max_length=500)


class ReverseIn(BaseModel):
    id: uuid.UUID
    comment: Comment = ""
    allow_negative: bool = False


class ReverseKey(BaseModel):
    """Idempotency key material for a reversal: the target document plus the request body."""

    original: uuid.UUID
    body: ReverseIn


# ----------------------------------------------------------------------- output
class DocLineOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    line_no: int
    product_id: int
    product_name: str
    product_sku: str
    unit: Unit
    base_unit: BaseUnit
    unit_size: Decimal
    location_from_id: int | None
    location_from_name: str | None
    location_to_id: int | None
    location_to_name: str | None
    qty_base: Decimal
    unit_price: Decimal | None
    unit_cost_base: Decimal | None
    amount: Decimal  # |qty_base| * unit_cost_base, unrounded


class DocOut(BaseModel):
    price_rate: Decimal | None = None  # receipts priced in dollars: won per dollar used
    sales_import_id: uuid.UUID | None = None  # compensation of a POS report corrected after an inventory
    id: uuid.UUID
    type: DocType
    status: DocStatus
    doc_date: datetime
    reason: WriteOffReason | None
    supplier: str | None
    invoice_no: str | None
    comment: str
    reversal_of: uuid.UUID | None
    reversed_by: uuid.UUID | None
    allow_negative: bool
    backdate_confirmed: bool
    created_by: int
    created_by_name: str
    created_at: datetime
    posted_at: datetime | None
    inventory_id: int | None
    total_amount: Decimal
    lines: list[DocLineOut]


class DocSummary(BaseModel):
    id: uuid.UUID
    type: DocType
    doc_date: datetime
    reason: WriteOffReason | None
    supplier: str | None
    invoice_no: str | None
    comment: str
    reversal_of: uuid.UUID | None
    reversed_by: uuid.UUID | None
    created_by_name: str
    posted_at: datetime | None
    line_count: int
    total_amount: Decimal


class DocPage(BaseModel):
    items: list[DocSummary]
    total: int


class MovementOut(BaseModel):
    id: int
    document_id: uuid.UUID
    doc_type: DocType
    reason: WriteOffReason | None
    doc_date: datetime
    created_at: datetime
    product_id: int
    product_name: str
    product_sku: str
    unit: Unit
    base_unit: BaseUnit
    unit_size: Decimal
    location_id: int
    location_name: str
    delta_base: Decimal
    balance_after: Decimal
    unit_cost_base: Decimal
    amount: Decimal  # signed delta * cost, unrounded
    user_name: str
    comment: str


class MovementPage(BaseModel):
    items: list[MovementOut]
    total: int


class StockRow(BaseModel):
    product_id: int
    product_name: str
    product_sku: str
    category_code: str | None
    category_name: str
    unit: Unit
    base_unit: BaseUnit
    unit_size: Decimal
    location_id: int
    location_name: str
    qty_base: Decimal
    value: Decimal  # current-price valuation, unrounded
    min_stock_base: Decimal = Decimal(0)
    is_low_stock: bool = False  # the product's total over all locations is at or below its minimum


class ReconcileRow(BaseModel):
    product_id: int
    location_id: int
    balance: Decimal
    journal_sum: Decimal


class DateRange(BaseModel):
    date_from: date | None = None
    date_to: date | None = None
