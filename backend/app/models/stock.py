import enum
import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import BigInteger, Boolean, DateTime, Enum, ForeignKey, Integer, Numeric, String, Text, Uuid, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db import Base


class DocType(str, enum.Enum):
    receipt = "receipt"
    write_off = "write_off"
    transfer = "transfer"
    inventory_adjustment = "inventory_adjustment"
    reversal = "reversal"


class DocStatus(str, enum.Enum):
    draft = "draft"
    posted = "posted"


class WriteOffReason(str, enum.Enum):
    spoilage = "spoilage"
    expired = "expired"
    breakage = "breakage"
    staff_use = "staff_use"
    other = "other"


class StockBalance(Base):
    """Cache of the movement journal: qty_base == SUM(stock_movements.delta_base) for the pair."""

    __tablename__ = "stock_balances"

    product_id: Mapped[int] = mapped_column(ForeignKey("products.id"), primary_key=True)
    location_id: Mapped[int] = mapped_column(ForeignKey("locations.id"), primary_key=True)
    qty_base: Mapped[Decimal] = mapped_column(Numeric(14, 3), default=Decimal("0"))
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())


class StockDocument(Base):
    __tablename__ = "stock_documents"

    # Generated by the client: a retried POST with the same id is idempotent.
    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True)
    type: Mapped[DocType] = mapped_column(Enum(DocType, name="doc_type"))
    status: Mapped[DocStatus] = mapped_column(Enum(DocStatus, name="doc_status"), default=DocStatus.draft)
    doc_date: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    reason: Mapped[WriteOffReason | None] = mapped_column(Enum(WriteOffReason, name="write_off_reason"))
    supplier: Mapped[str | None] = mapped_column(String(128))
    invoice_no: Mapped[str | None] = mapped_column(String(64))
    comment: Mapped[str] = mapped_column(Text, default="")
    reversal_of: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("stock_documents.id"), unique=True)
    allow_negative: Mapped[bool] = mapped_column(Boolean, default=False)
    backdate_confirmed: Mapped[bool] = mapped_column(Boolean, default=False)
    # sha256 of the canonical create request (idempotent retries); NULL for system documents.
    request_hash: Mapped[str | None] = mapped_column(String(64))
    created_by: Mapped[int] = mapped_column(ForeignKey("users.id"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    posted_by: Mapped[int | None] = mapped_column(ForeignKey("users.id"))
    posted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    lines: Mapped[list["StockDocumentLine"]] = relationship(
        back_populates="document", order_by="StockDocumentLine.line_no", cascade="all, delete-orphan"
    )


class StockDocumentLine(Base):
    __tablename__ = "stock_document_lines"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    document_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("stock_documents.id", ondelete="CASCADE"))
    line_no: Mapped[int] = mapped_column(Integer)
    product_id: Mapped[int] = mapped_column(ForeignKey("products.id"))
    location_from_id: Mapped[int | None] = mapped_column(ForeignKey("locations.id"))
    location_to_id: Mapped[int | None] = mapped_column(ForeignKey("locations.id"))
    # > 0 for every type except inventory_adjustment (signed, != 0).
    qty_base: Mapped[Decimal] = mapped_column(Numeric(14, 3))
    # Receipt: price per product unit exactly as entered.
    unit_price: Mapped[Decimal | None] = mapped_column(Numeric(14, 2))
    unit_cost_base: Mapped[Decimal | None] = mapped_column(Numeric(18, 6))

    document: Mapped[StockDocument] = relationship(back_populates="lines")


class StockMovement(Base):
    """Append-only journal (UPDATE/DELETE are rejected by a database trigger)."""

    __tablename__ = "stock_movements"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    document_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("stock_documents.id"))
    product_id: Mapped[int] = mapped_column(ForeignKey("products.id"))
    location_id: Mapped[int] = mapped_column(ForeignKey("locations.id"))
    delta_base: Mapped[Decimal] = mapped_column(Numeric(14, 3))
    unit_cost_base: Mapped[Decimal] = mapped_column(Numeric(18, 6))
    balance_after: Mapped[Decimal] = mapped_column(Numeric(14, 3))
    doc_date: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"))
